// Arithmetic Operations
let a = 10;
let b = 5;
console.log(a + b);
console.log(a - b);
console.log(a * b);
console.log(a / b);
console.log(a % b);
console.log(a ** b);

//Unary Operators
console.log(a++);
console.log(++a);

//Comparison Operators
console.log(a>b);
console.log(a<=b);
console.log(a==b);
console.log(a!=b);
console.log(5=='5');
console.log(5==='5');